async function addBlogs() {
  console.log(`Starting API calls to: ${API_BASE}\n`);

  // 1. Fetch categories
  const catRes = await fetch(`${API_BASE}/categories`);
  const catData = await catRes.json();
  const catMap = {};
  if (catData.categories) {
    for (const c of catData.categories) {
      catMap[c.slug] = c._id;
      catMap[c.name.toLowerCase()] = c._id;
    }
  }
  console.log("Categories loaded:", Object.keys(catMap));

  const createdList = [];

  for (let i = 0; i < blogsToSeed.length; i++) {
    const item = blogsToSeed[i];
    let token = "";

    // 2. Register or Login author
    try {
      const regRes = await fetch(`${API_BASE}/auth/register`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: item.author.name,
          email: item.author.email,
          password: item.author.password,
          avatar: item.author.avatar,
        }),
      });

      const regData = await regRes.json();

      if (regRes.ok && regData.token) {
        token = regData.token;
        console.log(`[${i + 1}/8] Registered author: "${item.author.name}"`);
      } else {
        // Try login
        const loginRes = await fetch(`${API_BASE}/auth/login`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            email: item.author.email,
            password: item.author.password,
          }),
        });

        const loginData = await loginRes.json();
        if (loginRes.ok && loginData.token) {
          token = loginData.token;
          console.log(`[${i + 1}/8] Logged in author: "${item.author.name}"`);
        } else {
          console.error(`Failed auth for ${item.author.name}:`, loginData);
          continue;
        }
      }
    } catch (err) {
      console.error(`Network error for author ${item.author.name}:`, err.message);
      continue;
    }

    // 3. Resolve category ID
    const categoryId = catMap[item.blog.categorySlug];
    if (!categoryId) {
      console.error(`Category not found for slug: ${item.blog.categorySlug}`);
      continue;
    }

    // 4. Call POST /api/blogs to add the blog
    try {
      const blogRes = await fetch(`${API_BASE}/blogs`, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${token}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          title: item.blog.title,
          excerpt: item.blog.excerpt,
          content: item.blog.content,
          category: categoryId,
          tags: item.blog.tags,
          coverImage: item.blog.coverImage,
          status: "published",
        }),
      });

      const blogData = await blogRes.json();

      if (blogRes.ok && blogData.blog) {
        console.log(`   -> Created Blog: "${blogData.blog.title}"`);
        console.log(`      Blog ID: ${blogData.blog._id}`);
        console.log(`      Author: ${item.author.name}`);
        console.log(`      Category: ${item.blog.categorySlug}`);
        console.log(`      Slug: ${blogData.blog.slug}\n`);
        createdList.push({
          id: blogData.blog._id,
          title: blogData.blog.title,
          author: item.author.name,
          category: item.blog.categorySlug,
          slug: blogData.blog.slug,
        });
      } else {
        console.error(`   Failed to create blog "${item.blog.title}":`, blogData);
      }
    } catch (err) {
      console.error(`   Network error creating blog "${item.blog.title}":`, err.message);
    }
  }

  console.log(`\n==========================================`);
  console.log(`Successfully created ${createdList.length} blogs via API!`);
  console.log(`==========================================`);
  console.log(JSON.stringify(createdList, null, 2));
}

addBlogs();
